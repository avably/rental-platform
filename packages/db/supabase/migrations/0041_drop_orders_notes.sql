-- 0041_drop_orders_notes.sql
-- Domknięcie długu z ADR-079: usunięcie martwej kolumny orders.notes i
-- przekierowanie OBU jej piszących do tabeli order_notes (0039). Decyzja
-- projektowa: ADR-081.
--
-- STAN PRZED: 0039 przeniósł notatki zamówienia do tabeli order_notes (lista
-- wpisów) i od tego czasu panel czyta WYŁĄCZNIE order_notes (notes-core.ts,
-- order-notes.tsx). Kolumna orders.notes została jednak w schemacie (świadek
-- danych źródłowych — dług odnotowany w ADR-079), a DWA writery nadal do niej
-- pisały:
--   * app.create_order (0016) — kreator zamówienia z panelu,
--   * app.public_checkout (0040) — checkout storefrontu (anon).
-- Skutek: każda notatka wpisana po 0039 (z kreatora LUB ze storefrontu)
-- lądowała w kolumnie, której UI już nie pokazuje — była NIEWIDOCZNA na liście
-- wpisów szczegółu zamówienia. To nie kosmetyka, to gubienie danych operatora.
--
-- CO ROBI TA MIGRACJA:
--   1. app.create_order — p_notes ZOSTAJE w sygnaturze (zgodność wsteczna
--      z wołającym: actions.ts nadal przekazuje p_notes), ale niepusta treść
--      tworzy WIERSZ w order_notes zamiast wpisu do martwej kolumny. Autor =
--      twórca zamówienia (auth.uid(); funkcja jest SECURITY INVOKER, więc
--      auth.uid() to zalogowany członek).
--   2. app.public_checkout — analogicznie, ale created_by = NULL (checkout jest
--      anonimowy — brak członka zespołu; UI pokaże „—", tak jak dla wpisów
--      historycznych przeniesionych w 0039).
--   3. DROP kolumny orders.notes — po przekierowaniu obu writerów nic już jej
--      nie pisze ani nie czyta (potwierdzone grepem: typy TS nie istnieją jako
--      wygenerowany plik, selecty szczegółu idą po order_notes, testy
--      przełączone na inną kolumnę w tym samym PR).
--
-- METODA (konwencje-migracji.md): obie funkcje odtworzone przez CREATE OR
-- REPLACE na NAJNOWSZYM ciele (create_order → 0016, public_checkout → 0040),
-- sygnatury BEZ ZMIAN, więc granty i tak przeżywają replace (nie re-wydajemy).
-- Ciała skopiowane w całości, nie okrojone — jedyna różnica merytoryczna to
-- zamiana zapisu kolumny notes na wpis do order_notes (uzasadnienie okrojenia:
-- nagłówek 0016). DROP kolumny na końcu, gdy nikt jej już nie dotyka.

-- ---------------------------------------------------------------------
-- 1. app.create_order — notatka kreatora → wpis w order_notes
-- ---------------------------------------------------------------------
--
-- Ciało IDENTYCZNE jak w 0016 (koszt dostawy w transporcie, stały porządek
-- pozycji, bramka pustego koszyka) z jedną zmianą: kolumna `notes` znika
-- z INSERT-a do orders, a niepusty p_notes zakłada wiersz w order_notes.
-- Sygnatura (10 argumentów) bez zmian → CREATE OR REPLACE, granty z 0016
-- (revoke public/anon, grant authenticated) obowiązują dalej.
create or replace function app.create_order(
  p_customer_id uuid,
  p_start_date date,
  p_end_date date,
  p_delivery_method text,
  p_pickup_location_id uuid,
  p_notes text,
  p_total_rental_grosze int,
  p_total_deposit_grosze int,
  p_items jsonb,
  p_delivery_grosze int default 0
) returns uuid
language plpgsql
security invoker
set search_path = pg_catalog, public, app
as $$
declare
  v_order_id uuid;
  r record;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Zamówienie wymaga co najmniej jednej pozycji.'
      using errcode = '22023';
  end if;

  insert into public.orders (
    tenant_id, customer_id, start_date, end_date, delivery_method,
    pickup_location_id, total_rental_grosze, total_deposit_grosze,
    delivery_grosze
  ) values (
    app.tenant_id(), p_customer_id, p_start_date, p_end_date, p_delivery_method,
    p_pickup_location_id,
    coalesce(p_total_rental_grosze, 0), coalesce(p_total_deposit_grosze, 0),
    coalesce(p_delivery_grosze, 0)
  )
  returning id into v_order_id;

  -- p_notes zostaje w sygnaturze (zgodność z wołającym sprzed 0041), ale
  -- niepusta treść tworzy WIERSZ w order_notes (0039), nie wpis do usuwanej
  -- niżej kolumny orders.notes. Autor = twórca zamówienia (auth.uid();
  -- SECURITY INVOKER → zalogowany członek). Pusta/„same spacje" notatka nie
  -- zakłada wpisu (btrim, jak filtr przeniesienia w 0039) — lista nie zbiera
  -- pustych wierszy, a CHECK body i tak by je odrzucił.
  if nullif(btrim(coalesce(p_notes, '')), '') is not null then
    insert into public.order_notes (tenant_id, order_id, body, created_by)
    values (app.tenant_id(), v_order_id, btrim(p_notes), auth.uid());
  end if;

  -- Stały porządek wstawiania (unit_id) = stały porządek blokad advisory —
  -- patrz komentarz przy zmianie terminu w app.orders_write_gate().
  for r in
    select
      (item ->> 'product_id')::uuid as product_id,
      nullif(item ->> 'unit_id', '')::uuid as unit_id,
      coalesce((item ->> 'rental_grosze')::int, 0) as rental_grosze,
      coalesce((item ->> 'deposit_grosze')::int, 0) as deposit_grosze
    from jsonb_array_elements(p_items) as item
    order by item ->> 'unit_id' nulls last
  loop
    insert into public.order_items (
      tenant_id, order_id, product_id, unit_id, rental_grosze, deposit_grosze
    ) values (
      app.tenant_id(), v_order_id, r.product_id, r.unit_id, r.rental_grosze, r.deposit_grosze
    );
  end loop;

  return v_order_id;
end;
$$;

